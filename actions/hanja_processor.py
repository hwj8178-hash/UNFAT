# 최장일치를 위해 길이 내림차순 정렬된 키 목록
_DICT_KEYS_SORTED = sorted(_DICT.keys(), key=len, reverse=True)


# ─── 공개 API ─────────────────────────────────────────────────────────────────

def detect_hanja_density(text: str) -> float:
    """
    텍스트에서 한자 비율을 반환합니다. (0.0 ~ 1.0)
    역사 자료에서 5% 이상이면 한자 병용 자료로 판단.
    """
    if not text:
        return 0.0
    hanja_count = len(_HANJA_CHAR_RE.findall(text))
    return hanja_count / max(len(text), 1)


def annotate_hanja(text: str) -> str:
    """
    한자를 '漢字(독음)' 형식으로 주석 달아 반환합니다.
    예: '朝鮮獨立運動' → '朝鮮(조선)獨立運動(독립운동)'

    사전에 있는 단어는 정확한 독음, 없는 단어는 글자별 독음.
    이미 한글이 병기된 경우 건드리지 않습니다.
    """
    if not text or not _HANJA_CHAR_RE.search(text):
        return text

    result = []
    i = 0
    while i < len(text):
        # 이미 (한글) 주석이 있으면 건너뜀
        if text[i] == '(' and i > 0 and _HANJA_CHAR_RE.match(text[i-1]):
            j = text.find(')', i)
            if j != -1:
                result.append(text[i:j+1])
                i = j + 1
                continue

        if _HANJA_CHAR_RE.match(text[i]):
            # 최장일치로 사전 탐색
            matched = False
            for key in _DICT_KEYS_SORTED:
                if text[i:i+len(key)] == key:
                    reading = _DICT[key]
                    # 이미 다음에 동일 독음이 있으면 중복 방지
                    after = text[i+len(key):]
                    if after.startswith(f'({reading})'):
                        result.append(key)
                    else:
                        result.append(f'{key}({reading})')
                    i += len(key)
                    matched = True
                    break
            if not matched:
                # 사전에 없는 단일 한자 — 글자 그대로 유지
                result.append(text[i])
                i += 1
        else:
            result.append(text[i])
            i += 1

    return ''.join(result)


def translate_to_korean(text: str, keep_original: bool = False) -> str:
    """
    한자를 한국어 독음으로 변환합니다.

    keep_original=True:  '朝鮮獨立' → '조선독립[朝鮮獨立]'
    keep_original=False: '朝鮮獨立' → '조선독립'

    규칙:
      - 사전 등재 단어는 정해진 독음으로만 변환 (유사어 대체 절대 금지)
      - 사전에 없는 단자는 원문 유지
    """
    if not text or not _HANJA_CHAR_RE.search(text):
        return text

    result = []
    i = 0
    while i < len(text):
        if _HANJA_CHAR_RE.match(text[i]):
            matched = False
            for key in _DICT_KEYS_SORTED:
                if text[i:i+len(key)] == key:
                    reading = _DICT[key]
                    if keep_original:
                        result.append(f'{reading}[{key}]')
                    else:
                        result.append(reading)
                    i += len(key)
                    matched = True
                    break
            if not matched:
                result.append(text[i])  # 사전 없는 한자는 원문 유지
                i += 1
        else:
            result.append(text[i])
            i += 1

    return ''.join(result)


def extract_hanja_glossary(text: str) -> list[dict]:
    """
    텍스트에서 등장하는 한자 단어 목록(용어집)을 추출합니다.
    Claude 프롬프트에 삽입하여 정확한 독음을 강제합니다.

    Returns: [{"hanja": "朝鮮", "reading": "조선", "count": 5}, ...]
    """
    if not text:
        return []

    found: dict[str, int] = {}
    i = 0
    while i < len(text):
        if _HANJA_CHAR_RE.match(text[i]):
            matched = False
            for key in _DICT_KEYS_SORTED:
                if len(key) >= 2 and text[i:i+len(key)] == key:
                    found[key] = found.get(key, 0) + 1
                    i += len(key)
                    matched = True
                    break
            if not matched:
                i += 1
        else:
            i += 1

    return [
        {"hanja": k, "reading": _DICT[k], "count": v}
        for k, v in sorted(found.items(), key=lambda x: -x[1])
        if v >= 1
    ]


def build_hanja_guide_for_prompt(text: str) -> str:
    """
    Claude 프롬프트에 삽입할 한자 독음 가이드 블록을 생성합니다.
    이 블록을 보고 Claude가 한자를 정확히 읽습니다.
    """
    glossary = extract_hanja_glossary(text)
    if not glossary:
        return ""

    lines = [
        "【한자 독음 대조표 — 이 자료에 등장하는 한자】",
        "아래 한자는 반드시 지정된 독음으로만 읽으세요. 유사어·의역·다른 독음 절대 금지.",
        "",
    ]
    # 최대 60개 (프롬프트 과부하 방지)
    for item in glossary[:60]:
        lines.append(f"  {item['hanja']} → {item['reading']}")

    unknown = _find_unknown_hanja(text)
    if unknown:
        lines.append("")
        lines.append("【사전 미등록 한자 — Claude가 문맥으로 독음 판단】")
        for h in unknown[:20]:
            lines.append(f"  {h}")

    return "\n".join(lines)


def _find_unknown_hanja(text: str) -> list[str]:
    """사전에 없는 한자 단어를 찾습니다."""
    unknown = set()
    i = 0
    while i < len(text):
        if _HANJA_CHAR_RE.match(text[i]):
            # 2글자 이상 연속 한자 추출
            j = i
            while j < len(text) and _HANJA_CHAR_RE.match(text[j]):
                j += 1
            chunk = text[i:j]
            if len(chunk) >= 2 and chunk not in _DICT:
                # 부분 매치 시도
                fully_matched = False
                for key in _DICT_KEYS_SORTED:
                    if chunk.startswith(key) or key.startswith(chunk):
                        fully_matched = True
                        break
                if not fully_matched:
                    unknown.add(chunk)
            i = j
        else:
            i += 1
    return sorted(unknown)
